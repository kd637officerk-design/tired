export const DIY_KEY = 'scoiatael_diy_themes_v1';

export function loadDIYThemes(): Record<string, ThemePreset> {
  const out: Record<string, ThemePreset> = {};
  try {
    const arr = JSON.parse(localStorage.getItem(DIY_KEY) || '[]');
    if (Array.isArray(arr)) {
      for (const item of arr) {
        if (item && typeof item.key === 'string' && /^custom_[a-z0-9_]+$/.test(item.key) && item.theme) {
          const t = item.theme;
          out[item.key] = {
            label: String(t.label || 'Custom Studio'),
            e: String(t.e || '✦'),
            accent: String(t.accent || '#ff7a1a'),
            secondaryAccent: t.secondaryAccent ? String(t.secondaryAccent) : undefined,
            bg: String(t.bg || '#060a0f'),
            chip: String(t.chip || 'rgba(16, 26, 36, 0.74)'),
            np: String(t.np || 'rgba(10, 17, 25, 0.9)'),
            sh: String(t.sh || 'rgba(12, 20, 29, 0.95)'),
            fg: String(t.fg || '#eef5f7'),
            pe: String(t.pe || t.accent || '#ffb36b'),
            mu: String(t.mu || '#98b0b8'),
            light: !!t.light,
            material: t.material || 'wet-glass',
            fx: t.fx || 'acid',
            holograms: t.holograms !== undefined ? !!t.holograms : true,
            wetGlass: t.wetGlass !== undefined ? !!t.wetGlass : true,
            crowd: t.crowd !== undefined ? !!t.crowd : true,
            crowdDensity: t.crowdDensity || 'active',
            backdropLandscape: t.backdropLandscape || AI_BACKDROPS[0].landscape,
            backdropPortrait: t.backdropPortrait || AI_BACKDROPS[0].portrait,
            l: String(t.l || ''),
            r: String(t.r || ''),
            tabs: Array.isArray(t.tabs) ? t.tabs : DEFAULT_TABS,
            empty: String(t.empty || 'Nothing here yet.'),
            font: t.font || '',
            corner: t.corner || '',
            layoutMode: t.layoutMode || 'default',
            isCustom: true,
          };
        }
      }
    }
  } catch {
    // ignore corrupted JSON
  }
  return out;
}

export function saveDIYThemes(customThemes: Record<string, ThemePreset>): boolean {
  try {
    const arr = Object.entries(customThemes)
      .filter(([k]) => k.startsWith('custom_'))
      .map(([key, theme]) => ({ key, theme }));
    localStorage.setItem(DIY_KEY, JSON.stringify(arr));
    return true;
  } catch {
    return false;
  }
}

export function deriveThemePaletteFromAccent(hex: string, light = false) {
  const m = /^#?([0-9a-f]{6})$/i.exec(hex || '');
  const clean = m ? '#' + m[1].toLowerCase() : '#ff7a1a';
  const n = parseInt(clean.slice(1), 16);
  const r = (n >> 16) / 255;
  const g = ((n >> 8) & 255) / 255;
  const b = (n & 255) / 255;
  const mx = Math.max(r, g, b);
  const mn = Math.min(r, g, b);
  const d = mx - mn;
  const l = (mx + mn) / 2;
  let h = 0;
  if (d) {
    h = mx === r ? ((g - b) / d) % 6 : mx === g ? (b - r) / d + 2 : (r - g) / d + 4;
    h = Math.round(h * 60);
    if (h < 0) h += 360;
  }
  const sat = d ? Math.round(Math.min(0.85, d / (1 - Math.abs(2 * l - 1))) * 100) : 0;

  if (light) {
    return {
      accent: clean,
      pe: clean,
      bg: `hsl(${h} 18% 95%)`,
      chip: `hsla(${h}, 20%, 100%, 0.82)`,
      np: `hsla(${h}, 20%, 98%, 0.94)`,
      sh: `hsla(${h}, 20%, 99%, 0.97)`,
      fg: '#141418',
      mu: '#52545d',
    };
  }

  return {
    accent: clean,
    pe: `hsl(${h} ${Math.max(sat, 30)}% 76%)`,
    bg: `hsl(${h} 34% 6%)`,
    chip: `hsla(${h}, 34%, 13%, 0.74)`,
    np: `hsla(${h}, 30%, 10%, 0.9)`,
    sh: `hsla(${h}, 32%, 11%, 0.95)`,
    fg: '#f1f5f8',
    mu: `hsl(${h} 16% 68%)`,
  };
}
